const field = (name, type, options = {}) => ({ name, type, ...options });

const id = () =>
  field("id", "uuid", {
    primary: true,
    required: true,
    default: "uuid",
    readonly: true,
    hidden: true,
  });

const publicationStatus = () =>
  field("status", "string", {
    required: true,
    default: "draft",
    choices: ["draft", "published", "archived"],
    index: true,
  });

const timestamps = () => [
  field("created_at", "timestamp", {
    special: ["date-created"],
    readonly: true,
    hidden: true,
  }),
  field("updated_at", "timestamp", {
    special: ["date-updated"],
    readonly: true,
    hidden: true,
  }),
];

const contentFields = (...fields) => [
  id(),
  publicationStatus(),
  ...fields,
  ...timestamps(),
];

