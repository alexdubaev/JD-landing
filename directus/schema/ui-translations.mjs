export const buildTranslations = (translation) => [ru(translation)];

export function getFieldTranslation(collection, field) {
  const translation = fieldTranslations[field];
  if (!translation) return null;
  return buildTranslations(translation);
}

export function getChoiceTranslations(field, choices = []) {
  return choices.map((choice) => ({
    text:
      choiceTranslations[`${field}.${choice.value}`] ?? choice.text,
    value: choice.value,
  }));
}
